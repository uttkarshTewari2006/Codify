@app.patch("/roadmaps/{roadmap_id}/reorder-tasks")
def reorder_tasks(
    roadmap_id: str,
    order_data: dict, # Expecting {"task_ids": [id1, id2, ...]}
    user_id: str = Depends(get_user_id),
    session: Session = Depends(get_session)
):
    """Updates the 'order' field for multiple tasks based on the provided list of IDs. Expects roadmap_id in URL and task_ids list in body. Returns success message."""
    roadmap = session.exec(select(Roadmap).where(Roadmap.id == roadmap_id, Roadmap.userId == user_id)).first()
    if not roadmap:
        raise HTTPException(status_code=404, detail="Roadmap not found")
        
    task_ids = order_data.get("task_ids", [])
    for index, tid in enumerate(task_ids):
        task = session.exec(select(Task).where(Task.id == tid, Task.roadmapId == roadmap_id)).first()
        if task:
            task.order = index
            session.add(task)
    
    session.commit()
    return {"message": "Order updated"}

