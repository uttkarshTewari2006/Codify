@app.post("/generate-plan")
def generate_plan(
    onboarding_data: dict, 
    user_id: str = Depends(get_user_id),
    session: Session = Depends(get_session)
):
    print(f"Generating plan for user: {user_id}")
    """
    1. Generates tasks using LangChain
    2. Saves a new Roadmap and its Tasks to the database
    3. Returns the generated plan
    """
    try:
        # Check if user exists in DB
        user = session.exec(select(User).where(User.id == user_id)).first()
        if not user:
            user = User(id=user_id, email="", onboarded=True)
            session.add(user)
            session.commit()

        # Generate tasks
        tasks_data = generate_roadmap_tasks(onboarding_data)
        
        # Create Roadmap
        target_role = onboarding_data.get('targetRole', 'Custom')
        if target_role == "Other":
            target_role = onboarding_data.get('otherRole', 'Custom')
            
        roadmap_id = str(uuid.uuid4())
        roadmap = Roadmap(
            id=roadmap_id,
            title=f"{target_role} Roadmap",
            description="Personalized roadmap generated by AI based on your onboarding.",
            userId=user_id
        )
        session.add(roadmap)
        
        # Create Tasks
        for t in tasks_data:
            task = Task(
                id=str(uuid.uuid4()),
                title=t['title'],
                description=t['description'],
                duration=t['duration'],
                type=t['type'],
                order=t['order'],
                deliverables=t.get('deliverables', []),
                links=t.get('links', []),
                roadmapId=roadmap_id
            )
            session.add(task)
        
        session.commit()
        return {"message": "Plan generated successfully", "roadmap_id": roadmap_id}
    except Exception as e:
        print(f"Error generating plan: {e}")
        raise HTTPException(status_code=500, detail="Failed to generate plan")


@app.post("/roadmaps/{roadmap_id}/regenerate")
def regenerate_plan(
    roadmap_id: str,
    payload: dict,
    user_id: str = Depends(get_user_id),
    session: Session = Depends(get_session)
):
    """
    Takes an existing roadmap ID, optional dashboard data, and a regenerate prompt.
    Uses the LLM to rewrite the tasks. Deletes old tasks and returns the new ones.
    """
    feedback = payload.get("feedback", "")
    existing_dashboard = payload.get("dashboard", {})

    roadmap = session.exec(select(Roadmap).where(Roadmap.id == roadmap_id, Roadmap.userId == user_id)).first()
    if not roadmap:
        raise HTTPException(status_code=404, detail="Roadmap not found")

    try:
        # Generate new tasks based on existing dashboard and feedback
        tasks_data = regenerate_roadmap_tasks(existing_dashboard, feedback)
        
        # Delete old tasks
        old_tasks = session.exec(select(Task).where(Task.roadmapId == roadmap_id)).all()
        for t in old_tasks:
            session.delete(t)
            
        # Create new Tasks
        for t in tasks_data:
            task = Task(
                id=str(uuid.uuid4()),
                title=t['title'],
                description=t['description'],
                duration=t['duration'],
                type=t['type'],
                order=t['order'],
                deliverables=t.get('deliverables', []),
                links=t.get('links', []),
                roadmapId=roadmap_id
            )
            session.add(task)
        
        session.commit()
        return {"message": "Plan regenerated successfully"}
    except Exception as e:
        print(f"Error regenerating plan: {e}")
        raise HTTPException(status_code=500, detail="Failed to regenerate plan")


