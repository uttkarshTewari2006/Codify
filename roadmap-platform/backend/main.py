@app.post("/roadmaps/{roadmap_id}/tasks")
def add_task(
    roadmap_id: str,
    task_data: dict,
    user_id: str = Depends(get_user_id),
    session: Session = Depends(get_session)
):
    """Adds a new task to a roadmap. Expects roadmap_id in URL and task details in JSON body. returns the created Task object."""
    roadmap = session.exec(select(Roadmap).where(Roadmap.id == roadmap_id, Roadmap.userId == user_id)).first()
    if not roadmap:
        raise HTTPException(status_code=404, detail="Roadmap not found")
    
    # Get max order to append
    tasks = session.exec(select(Task).where(Task.roadmapId == roadmap_id)).all()
    next_order = max([t.order for t in tasks], default=-1) + 1
    
    new_task = Task(
        id=str(uuid.uuid4()),
        title=task_data.get("title", "New Task"),
        description=task_data.get("description", ""),
        duration=task_data.get("duration", ""),
        type=task_data.get("type", "info"),
        deliverables=task_data.get("deliverables", None),
        links=task_data.get("links", None),
        order=next_order,
        roadmapId=roadmap_id
    )
    session.add(new_task)
    session.commit()
    session.refresh(new_task)
    return new_task

