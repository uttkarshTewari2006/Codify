def format_deliverables(deliverables):
    """Converts various deliverable formats (string list, tuple list) into the standard object format."""
    if not deliverables:
        return []
    
    formatted = []
    for d in deliverables:
        if isinstance(d, str):
            formatted.append({"title": d, "completed": False, "completedAt": None})
        elif isinstance(d, (list, tuple)) and len(d) >= 2:
            # Handle legacy [title, completed] format
            formatted.append({
                "title": d[0], 
                "completed": d[1], 
                "completedAt": datetime.utcnow().isoformat() if d[1] else None
            })
        elif isinstance(d, dict):
            # Already in new format or partial
            formatted.append({
                "title": d.get("title", ""),
                "completed": d.get("completed", False),
                "completedAt": d.get("completedAt")
            })
    return formatted


def normalize_task(task: Task) -> Task:
    """Ensures task JSON fields use the standard API shape before returning them."""
    task.deliverables = format_deliverables(task.deliverables)
    task.links = task.links or []
    return task


